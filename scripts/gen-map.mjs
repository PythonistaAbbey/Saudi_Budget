// Generates src/data/ksa-map.ts from Natural Earth (world-atlas, public domain).
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoMercator, geoPath } from "d3-geo";

const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/countries-50m.json", import.meta.url)));
const all = feature(topo, topo.objects.countries).features;
const ksa = all.find((f) => f.id === "682");
const W = 1000, H = 820;
const proj = geoMercator().fitExtent([[20, 20], [W - 20, H - 20]], ksa);
const path = geoPath(proj);
const r = (n) => Math.round(n * 10) / 10;
const ksaPath = path(ksa).replace(/(\d+\.\d+)/g, (m) => String(r(+m)));
const neighbourIds = ["368", "400", "414", "634", "784", "512", "887", "048", "818", "760", "376", "275", "232", "729"]; // IQ JO KW QA AE OM YE BH EG SY IL PS ER SD
const neighbours = all.filter((f) => neighbourIds.includes(String(f.id))).map((f) => path(f)).filter(Boolean).map((d) => d.replace(/(\d+\.\d+)/g, (m) => String(r(+m)))).join(" ");
const [k, tx, ty] = [proj.scale(), ...proj.translate()];
writeFileSync(
  new URL("../src/data/ksa-map.ts", import.meta.url),
  `// GENERATED by scripts/gen-map.mjs from Natural Earth via world-atlas (public domain). Do not edit.\nexport const MAP_W = ${W};\nexport const MAP_H = ${H};\nexport const MAP_SCALE = ${k};\nexport const MAP_TRANSLATE: [number, number] = [${tx}, ${ty}];\nexport const KSA_PATH = ${JSON.stringify(ksaPath)};\nexport const NEIGHBOURS_PATH = ${JSON.stringify(neighbours)};\n`,
);
console.log("ok", ksaPath.length, neighbours.length);
